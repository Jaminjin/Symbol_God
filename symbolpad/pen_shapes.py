"""Hand-drawn reference shapes: how people usually write common symbols.

Fonts don't always look like handwriting (a font's √ has no bar on top, for
example), so these pen-stroke versions are used as extra templates next to the
font glyphs.  Coordinates are in a unit box with y pointing down.
"""

import math

import numpy as np


def line(*pts):
    return ("line", pts)


def curve(*pts):
    return ("curve", pts)


def dot(x, y):
    return ("dot", ((x, y),))


def arc(cx, cy, rx, ry, a0, a1, n=40):
    a = np.radians(np.linspace(a0, a1, n))
    return ("line", tuple(zip(cx + rx * np.cos(a), cy + ry * np.sin(a))))


def _lemniscate():
    t = np.linspace(0, 2 * np.pi, 80)
    d = 1 + np.sin(t) ** 2
    return ("line", tuple(zip(0.5 + 0.47 * np.cos(t) / d, 0.5 + 0.55 * np.sin(t) * np.cos(t) / d)))


def _star():
    pts = [(0.5 + 0.48 * math.cos(math.radians(-90 + k * 144)),
            0.52 + 0.48 * math.sin(math.radians(-90 + k * 144))) for k in range(6)]
    return ("line", tuple(pts))


