def catmull_rom(pts, n=12):
    """Smooth curve through the control points."""
    p = np.asarray(pts, float)
    p = np.vstack([p[0], p, p[-1]])
    out = []
    for i in range(1, len(p) - 2):
        p0, p1, p2, p3 = p[i - 1], p[i], p[i + 1], p[i + 2]
        for t in np.linspace(0, 1, n, endpoint=False):
            out.append(0.5 * (2 * p1 + (p2 - p0) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t * t
                              + (3 * p1 - p0 - 3 * p2 + p3) * t * t * t))
    out.append(p[-2])
    return np.array(out)


def densify(pts, spacing=0.012):
    p = np.asarray(pts, float)
    out = [p[0]]
    for a, b in zip(p[:-1], p[1:]):
        n = max(int(np.hypot(*(b - a)) / spacing), 1)
        out.extend(a + (b - a) * t for t in np.linspace(0, 1, n + 1)[1:])
    return np.array(out)


def to_strokes(shape):
    """A shape definition as a list of (n, 2) point arrays, like real pen input."""
    strokes = []
    for kind, pts in shape:
        if kind == "dot":
            strokes.append(np.asarray(pts, float))
        else:
            strokes.append(densify(catmull_rom(pts) if kind == "curve" else pts))
    return strokes
